#!/usr/bin/env python3
"""Generate the shard modules of the upper-bound check from a dry-run cost profile.

Pieces of width w = floor(2^P/200) from lo0 = floor(r 2^P) were timed by the compiled checker (dry run, one line
"i ok ms" per piece).  Segments are formed so that each takes about TARGET ms: an expensive piece is split into q
sub-pieces of width floor(w/q) (q a power of two), cheap consecutive pieces are grouped.  The segment chain is exact
(each segment starts where the previous one ends) and ends at or beyond Y 2^P.  Nothing here is trusted: the Lean
checker verifies contiguity and coverage (baseOK) and every segment (segOK).
Usage: python3 -I gen_upper_shards.py DRYDIR OUTDIR TARGET_MS
Writes OUTDIR/SUCert/UpperCfg.lean, OUTDIR/SignUnc/UpperShards/S<j>.lean, OUTDIR/SignUnc/UpperMain.lean.
"""
import sys, os, glob, math

P, N_TAYLOR, K_DBL, RN, RD, YN, YD, DEPTH = 128, 24, 4, 5509, 10000, 92, 1, 30
W = 2 ** P // 200

def main(drydir, outdir, target):
    target = float(target)
    cost = {}
    for f in glob.glob(os.path.join(drydir, 'p_*.txt')):
        for line in open(f):
            parts = line.split()
            if len(parts) == 3 and parts[1] == 'true':
                cost[int(parts[0])] = float(parts[2])
    lo0 = RN * 2 ** P // RD
    end_needed = YN * 2 ** P  # need e * YD >= YN 2^P, YD = 1
    npieces = -(-(end_needed - lo0) // W)
    # pieces missing from an unfinished dry-run chunk get the largest known cost of their chunk of 100
    for i in range(npieces):
        if i not in cost:
            known = [cost[j] for j in range(100 * (i // 100), 100 * (i // 100) + 100) if j in cost]
            cost[i] = max(known) if known else 150000.0
    segs = []  # (lo, w, m)
    lo = lo0
    i = 0
    group_lo, group_m, group_cost = None, 0, 0.0
    def flush():
        nonlocal group_lo, group_m, group_cost
        if group_m:
            segs.append((group_lo, W, group_m))
        group_lo, group_m, group_cost = None, 0, 0.0
    while lo < end_needed:
        c = cost.get(i, cost[npieces - 1])
        if c > target:
            flush()
            q = 1 << max(0, math.ceil(math.log2(c / target)))
            wq = W // q
            # q sub-pieces as segments of one or more sub-pieces of about target cost
            per = max(1, int(target // (c / q)))
            k = 0
            while k < q:
                m = min(per, q - k)
                segs.append((lo, wq, m))
                lo += m * wq
                k += m
        else:
            if group_m == 0:
                group_lo = lo
            if group_cost + c > target and group_m > 0:
                flush()
                group_lo = lo
            group_m += 1
            group_cost += c
            lo += W
        i += 1
    flush()
    # exact chain check
    e = lo0
    for (l, w, m) in segs:
        assert l == e and w > 0 and m > 0
        e = l + m * w
    assert e * YD >= end_needed
    os.makedirs(os.path.join(outdir, 'SUCert'), exist_ok=True)
    os.makedirs(os.path.join(outdir, 'SignUnc', 'UpperShards'), exist_ok=True)
    cfg = [f"import SUCert.Chk", "",
           "/-! Generated by tools/gen_upper_shards.py: run parameters and the segment chain of the upper-bound check. -/",
           "", "namespace SignUnc.UpperRun", "open SignUnc.Chk", "",
           "/-- P n k rn rd Yn Yd w cnt depth (w, cnt unused by the sharded check). -/",
           f"def cfgU : Cfg := ⟨{P}, {N_TAYLOR}, {K_DBL}, {RN}, {RD}, {YN}, {YD}, {W}, {npieces}, {DEPTH}⟩", "",
           "def segsU : List Seg := ["]
    cfg.append(",\n".join(f"  (⟨{l}, {w}, {m}⟩ : Seg)" for (l, w, m) in segs))
    cfg += ["]", "", "end SignUnc.UpperRun", ""]
    open(os.path.join(outdir, 'SUCert', 'UpperCfg.lean'), 'w').write("\n".join(cfg))
    for j, (l, w, m) in enumerate(segs):
        txt = ["import SUCert.UpperCfg", "import SUCert.DataUpper", "",
               "namespace SignUnc.UpperRun", "open SignUnc.Chk SignUnc.Data", "",
               f"theorem shardU_{j} : segOK cfgU upperData (⟨{l}, {w}, {m}⟩ : Seg) = true := by native_decide", "",
               "end SignUnc.UpperRun", ""]
        open(os.path.join(outdir, 'SignUnc', 'UpperShards', f'S{j}.lean'), 'w').write("\n".join(txt))
    main_txt = ["import SignUnc.ChkSound", "import SUCert.UpperCfg", "import SUCert.DataUpper"]
    main_txt += [f"import SignUnc.UpperShards.S{j}" for j in range(len(segs))]
    main_txt += ["", "/-!", "# `A₊(1)² ≤ 0.5509²` and `C_{6.11} ≤ 0.5509²` (track N: native_decide)", "-/", "",
                 "namespace SignUnc.UpperRun", "open SignUnc SignUnc.Chk SignUnc.Data", "",
                 "theorem baseU : baseOK cfgU upperData segsU = true := by native_decide", "",
                 "set_option maxRecDepth 100000 in",
                 "theorem shardsU : List.Forall (fun s => segOK cfgU upperData s = true) segsU :=",
                 "  ⟨" + ", ".join(f"shardU_{j}" for j in range(len(segs))) + "⟩", "",
                 "end SignUnc.UpperRun", "", "namespace SignUnc", "open SignUnc.Chk SignUnc.Data SignUnc.UpperRun", "",
                 "/-- The upper half of Theorem 1.1 of the paper. -/",
                 "theorem upper : UpperStatement := by",
                 "  obtain ⟨hL, h0, hpos⟩ := upper_sharded_sound cfgU upperData segsU baseU shardsU",
                 "  have hr : ((cfgU.rn : ℝ) / cfgU.rd) = 5509 / 10000 := by norm_num [cfgU]",
                 "  exact upper_of_gsum (r := 5509 / 10000) (by norm_num) _ hL h0",
                 "    (fun y hy => (hpos y (by rw [hr]; exact hy)).le)", "",
                 "end SignUnc", ""]
    open(os.path.join(outdir, 'SignUnc', 'UpperMain.lean'), 'w').write("\n".join(main_txt))
    tot = sum(cost.get(i, 0) for i in range(npieces))
    print(f"{len(segs)} segments, {npieces} base pieces, dry-run total {tot/1000:.0f} s, max piece {max(cost.values())/1000:.1f} s")

if __name__ == '__main__':
    main(*sys.argv[1:4])
