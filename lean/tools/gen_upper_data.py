#!/usr/bin/env python3
"""Generate SUCert/DataUpper.lean from the upper-bound certificate (pcert JSON, read-only input).

Each pair (a, s, c) becomes `GT.mk an ad sn sd cn cd` with a = an/ad, s = sn/sd, c = cn/cd in lowest terms;
the wide pair (the unique smallest a) is put FIRST, the other pairs keep their order.  Negative integers are
written `Int.negSucc k` (fast elaboration).  Chunks of 128 pairs, each element ascribed.
Usage: python3 -I gen_upper_data.py CERT.json OUT.lean
"""
import json, sys, hashlib
from fractions import Fraction

def lit_int(n):
    return f"(Int.negSucc {-n - 1})" if n < 0 else f"({n} : Int)"

def main(cert, out):
    raw = open(cert, 'rb').read()
    d = json.loads(raw)
    terms = [(Fraction(a), Fraction(s), Fraction(c)) for a, s, c in d["gauss"]]
    amin = min(t[0] for t in terms)
    wide = [t for t in terms if t[0] == amin]
    assert len(wide) == 1
    rest = [t for t in terms if t[0] != amin]
    order = wide + rest
    lines = ["import SUCert.Chk", "",
             "/-! Generated by tools/gen_upper_data.py from " + cert.split('/')[-1] +
             f" (sha256 {hashlib.sha256(raw).hexdigest()}); wide pair first. -/", "",
             "namespace SignUnc.Data", "open SignUnc.Chk", ""]
    chunks = [order[i:i + 128] for i in range(0, len(order), 128)]
    for ci, ch in enumerate(chunks):
        lines.append(f"def upperChunk{ci} : List GT := [")
        items = []
        for a, s, c in ch:
            assert a > 0 and s >= 0
            items.append(f"  (GT.mk {a.numerator} {a.denominator} {lit_int(s.numerator)} {s.denominator} "
                         f"{lit_int(c.numerator)} {c.denominator} : GT)")
        lines.append(",\n".join(items))
        lines.append("]")
        lines.append("")
    lines.append("def upperData : List GT := " + " ++ ".join(f"upperChunk{ci}" for ci in range(len(chunks))))
    lines.append("")
    lines.append("end SignUnc.Data")
    open(out, 'w').write("\n".join(lines) + "\n")
    print(f"{len(order)} pairs, {len(chunks)} chunks -> {out}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
